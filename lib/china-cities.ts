// 去掉 市/区/县/盟/州/省 等后缀，做核心名匹配
function normalizeCity(name: string): string {
  if (!name) return '';
  let s = name.trim();
  // 去掉末尾行政单位后缀
  s = s.replace(/(市|区|县|盟|州|省)$/g, '');
  // 去掉「自治区」整词
  s = s.replace(/自治区$/, '');
  // 去掉「特别行政区」
  s = s.replace(/特别行政区$/, '');
  return s;
}

/** 根据城市名返回 [lng,lat]；未命中返回 null */
export function cityCoord(name: string): LngLat | null {
  const core = normalizeCity(name);
  if (CITY_COORDS[core]) return CITY_COORDS[core];
  // 兜底：尝试省份
  if (PROVINCE_CENTROID[core]) return PROVINCE_CENTROID[core];
  // 尝试国外国家
  if (COUNTRY_COORDS[core]) return COUNTRY_COORDS[core];
  // 城市名里含省份（如 "湖北武汉" 不太可能，但防一手）
  for (const prov of Object.keys(PROVINCE_CENTROID)) {
    if (core.includes(prov)) return PROVINCE_CENTROID[prov];
  }
  return null;
}

